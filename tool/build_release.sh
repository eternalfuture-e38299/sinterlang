#!/bin/sh
# Build and package the self-hosted Sinter toolchain for every supported
# platform/architecture combination.
#
#   sh tool/build_release.sh [name ...]
#
# With no arguments all 13 targets are built. A subset can be selected with
# names such as `linux.x64` or `android.arm64`.
#
# Output: build/<platform>.<arch>.zip, each containing sinter, sinterc,
# sinterd, sinter-lsp plus LICENSE/VERSION/README.txt.
set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT="$ROOT/build"
VERSION=$(cat "$ROOT/VERSION")
JOBS=${SINTER_JOBS:-8}
TOOL=${SINTER:-/home/eternalfuture/bin/sinter/sinter}
HOSTC=${SINTERC:-/home/eternalfuture/bin/sinter/sinterc}
NDK_CC="$ROOT/tool/android-ndk-cc.sh"

ALL="linux.x64 linux.x86 linux.arm64 linux.arm windows.x64 windows.x86 windows.arm64 macos.x86 macos.arm64 android.arm64 android.arm android.x64 android.x86"
NAMES=${*:-$ALL}

command -v zig >/dev/null 2>&1 || { echo "error: zig not found"; exit 1; }
command -v zip >/dev/null 2>&1 || { echo "error: zip not found"; exit 1; }
[ -x "$TOOL" ] || { echo "error: sinter not executable: $TOOL"; exit 1; }
[ -x "$HOSTC" ] || { echo "error: sinterc not executable: $HOSTC"; exit 1; }
[ -x "$NDK_CC" ] || { echo "error: NDK wrapper not executable: $NDK_CC"; exit 1; }

mkdir -p "$OUT/logs"
WORK=${TMPDIR:-/tmp}/sinter_release_$$
mkdir -p "$WORK"

target_for() {
    case "$1" in
        linux.x64)     echo x86_64-linux-gnu ;;
        linux.x86)     echo x86-linux-gnu ;;
        linux.arm64)   echo aarch64-linux-gnu ;;
        linux.arm)     echo arm-linux-gnueabihf ;;
        windows.x64)   echo x86_64-windows-gnu ;;
        windows.x86)   echo x86-windows-gnu ;;
        windows.arm64) echo aarch64-windows-gnu ;;
        macos.x86)     echo x86_64-macos-none ;;
        macos.arm64)   echo aarch64-macos-none ;;
        android.arm64) echo aarch64-linux-android24 ;;
        android.arm)   echo armv7a-linux-androideabi24 ;;
        android.x64)   echo x86_64-linux-android24 ;;
        android.x86)   echo i686-linux-android24 ;;
        *) return 1 ;;
    esac
}

compiler_for() {
    case "$1" in
        android.*) echo "$NDK_CC" ;;
        *) echo zig ;;
    esac
}

platform_for() { echo "${1%%.*}"; }
arch_for() { echo "${1#*.}"; }

for name in $NAMES; do
    target=$(target_for "$name") || { echo "error: unknown target name: $name"; exit 1; }
    compiler=$(compiler_for "$name")
    echo "== $name ($target) =="

    stage="$WORK/$name"
    mkdir -p "$stage"

    for p in sinter sinterc sinterd sinter-lsp; do
        build_dir="build/release/$name"
        log="$OUT/logs/$name-$p.log"
        rm -rf "$ROOT/src/$p/$build_dir"
        if (cd "$ROOT/src/$p" \
            && SINTERC="$HOSTC" SINTER_TARGET="$target" SINTER_ZIG="$compiler" \
               SINTER_BUILD_DIR="$build_dir" "$TOOL" build -j "$JOBS") >"$log" 2>&1; then
            artifact="$ROOT/src/$p/$build_dir/$p"
            [ -f "$artifact" ] || artifact="$artifact.exe"
            if [ ! -f "$artifact" ]; then
                echo "  [FAIL] $p (missing artifact)"
                tail -20 "$log"
                exit 1
            fi
            cp "$artifact" "$stage/"
            echo "  [ OK ] $p"
        else
            echo "  [FAIL] $p"
            tail -30 "$log"
            exit 1
        fi
    done

    cat > "$stage/README.txt" <<EOF
Sinter $VERSION release bundle

platform: $(platform_for "$name")
arch:     $(arch_for "$name")
target:   $target
compiler: $compiler
tools:    sinter, sinterc, sinterd, sinter-lsp

Generated by tool/build_release.sh.
EOF
    cp "$ROOT/LICENSE" "$ROOT/VERSION" "$stage/"

    rm -f "$OUT/$name.zip"
    (cd "$stage" && zip -q -r "$OUT/$name.zip" .)
    echo "  packaged $OUT/$name.zip"
done

echo
echo "release packages:"
for name in $NAMES; do
    ls -lh "$OUT/$name.zip"
done
